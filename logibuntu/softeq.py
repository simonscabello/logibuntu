"""Software EQ through a PipeWire filter-chain sink.

The G533 accepts gains on HID++ 0x8310 but does not apply them to audio (G HUB equalizes in software),
so we insert a virtual sink "<headset> (Equalizador)" in front of the headset sink.
"""
import json
import os
import re
import subprocess
import time

CONF = os.path.expanduser("~/.config/pipewire/pipewire.conf.d/logibuntu-eq.conf")
NODE = "logibuntu_eq"
Q = 1.41  # about one octave per band, matching the headset's octave-spaced bands


def _dump():
    return json.loads(subprocess.run(["pw-dump"], capture_output=True, text=True, check=True).stdout)


def _props(o):
    return o.get("info", {}).get("props", {}) if o.get("type", "").endswith(":Node") else {}


def _target(media_class, match):
    for o in _dump():
        p = _props(o)
        if (p.get("media.class") == media_class and match in p.get("node.description", "")
                and not p.get("node.name", "").startswith("logibuntu_")):
            return p["node.name"]
    return None


def target_sink(match):
    """node.name of the real headset sink (description contains `match`)."""
    return _target("Audio/Sink", match)


def node_id(name=NODE):
    return next((o["id"] for o in _dump() if _props(o).get("node.name") == name), None)


def enabled():
    return os.path.exists(CONF)


def saved_gains():
    try:
        return json.loads(re.search(r"^# gains: (.*)$", open(CONF).read(), re.M).group(1))
    except (OSError, AttributeError, ValueError):
        return None


def render(target, label, freqs, gains):
    nodes = "\n".join(
        f'{{ type = builtin name = eq_band_{i + 1} label = bq_peaking '
        f'control = {{ "Freq" = {float(f)} "Q" = {Q} "Gain" = {float(g)} }} }}'
        for i, (f, g) in enumerate(zip(freqs, gains)))
    links = "\n".join(f'{{ output = "eq_band_{i}:Out" input = "eq_band_{i + 1}:In" }}' for i in range(1, len(freqs)))
    return f"""# Generated by logibuntu; delete this file to remove the equalizer.
# gains: {json.dumps(list(gains))}
context.modules = [
{{ name = libpipewire-module-filter-chain
  args = {{
    node.description = "{label} (Equalizador)"
    media.name = "{label} (Equalizador)"
    filter.graph = {{
      nodes = [
{nodes}
      ]
      links = [
{links}
      ]
    }}
    audio.channels = 2
    audio.position = [ FL FR ]
    capture.props = {{ node.name = "{NODE}" media.class = Audio/Sink }}
    playback.props = {{ node.name = "{NODE}.output" node.passive = true
                        target.object = "{target}" node.dont-fallback = true }}
  }}
}}
]
"""


def _write(text, path=CONF):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def _restart_pipewire():
    subprocess.run(["systemctl", "--user", "restart", "pipewire.service", "pipewire-pulse.service",
                    "wireplumber.service"], check=True)


def _restart_and_default(name):
    _restart_pipewire()
    for _ in range(50):  # WirePlumber needs a moment after the restart before it accepts set-default
        nid = node_id(name)
        if nid and subprocess.run(["wpctl", "set-default", str(nid)], capture_output=True).returncode == 0:
            return nid
        time.sleep(0.2)
    raise RuntimeError(f"o PipeWire não criou {name}; veja `journalctl --user -u pipewire`")


def enable(target, label, freqs, gains):
    """Create the EQ sink (restarts PipeWire once, ~1 s of silence) and make it the default output."""
    _write(render(target, label, freqs, gains))
    return _restart_and_default(NODE)


def disable():
    if enabled():
        os.remove(CONF)
        _restart_pipewire()


def set_gains(target, label, freqs, gains):
    """Live update without restarting PipeWire; the file keeps it for the next login."""
    nid = node_id()
    if nid is None:
        raise RuntimeError("equalizador não está ativo no PipeWire")
    params = " ".join(f'"eq_band_{i + 1}:Gain" {float(g)}' for i, g in enumerate(gains))
    subprocess.run(["pw-cli", "s", str(nid), "Props", f"{{ params = [ {params} ] }}"],
                   check=True, capture_output=True)
    _write(render(target, label, freqs, gains))

